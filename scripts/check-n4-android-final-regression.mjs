import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';

const signed='downloads/campsite-bridge-android-0.3.5.xpi';
assert.equal(crypto.createHash('sha256').update(fs.readFileSync(signed)).digest('hex'),'f5c7d300c6cdd82758f88f651116c1b7af42863ef03e80f8ac89e39afa0fa7b7');
execFileSync(process.execPath,['scripts/build-android-bridge-0.3.7-unsigned.mjs'],{stdio:'inherit'});
const xpi='downloads/campsite-bridge-android-0.3.7-unsigned.xpi';
const manifest=JSON.parse(execFileSync('unzip',['-p',xpi,'manifest.json'],{encoding:'utf8'}));
assert.equal(manifest.version,'0.3.7');
const page=manifest.content_scripts.find(x=>x.world==='MAIN');
const isolated=manifest.content_scripts.find(x=>x.world==='ISOLATED');
assert.ok(page&&isolated);
for(const f of ['page-hook.js','wayfarer-map-adapter.js','wayfarer-observation-zone.js','wayfarer-acquisition-engine.js','wayfarer-polygon-controller.js','wayfarer-acquisition-coordinator.js']) assert.ok(page.js.includes(f),f+' missing MAIN');
for(const f of ['bridge-core.js','polygon-ui.js','panel-polygon-adapter.js','bridge-ui.js','panel-ui-adapter.js']) assert.ok(isolated.js.includes(f),f+' missing ISOLATED');
const names=execFileSync('unzip',['-Z1',xpi],{encoding:'utf8'}).trim().split(/\n/);
let all=''; for(const n of names.filter(n=>n.endsWith('.js'))) all+=execFileSync('unzip',['-p',xpi,n],{encoding:'utf8'});
assert.doesNotMatch(all,/campsite-bridge-pc:polygon-(?:command|state)/,'PC polygon namespace leaked');
assert.match(all,/campsite-bridge-android-n4:polygon-command/);
assert.match(all,/BUFFER_METERS = 200/);
assert.match(all,/WAYFARER_OBSERVATION/);
assert.match(all,/wayfarerObservation/);
assert.match(all,/CAMPSITE_BRIDGE_POI_V1/);
assert.match(all,/receiver\.postMessage\(payload, RECEIVER_ORIGIN\)/);
assert.doesNotMatch(all,/Bridge POI Overlay|bridge-poi-overlay/i,'Bridge POI Overlay appears to have returned');
const n4Added=['wayfarer-map-adapter.js','wayfarer-observation-zone.js','wayfarer-acquisition-engine.js','wayfarer-polygon-controller.js','wayfarer-acquisition-coordinator.js','polygon-ui.js','panel-polygon-adapter.js','panel-ui-adapter.js'];
let n4Text=''; for(const n of n4Added) n4Text+=execFileSync('unzip',['-p',xpi,n],{encoding:'utf8'});
assert.doesNotMatch(n4Text,/new\s+(?:google\.maps\.)?(?:Marker|AdvancedMarkerElement)\s*\(/,'N4 code must not create POI markers');
const builder=fs.readFileSync('scripts/build-android-bridge-0.3.7-unsigned.mjs','utf8');
assert.doesNotMatch(builder,/creative\//i);
console.log('N4 Android E-G final regression PASS');
