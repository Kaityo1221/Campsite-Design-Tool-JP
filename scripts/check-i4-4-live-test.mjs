import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';
for(const path of ['lab/i4-4-live-test.js','lab/i4-4-iphone-test-shortcut.js','bridge-pc/wayfarer-acquisition-engine.js']) {
 execFileSync(process.execPath,['--check',path]);
}
const source=fs.readFileSync('bridge-pc/wayfarer-acquisition-engine.js','utf8');
const context={window:{}};vm.runInNewContext(source,context);
const engine=context.window.CampsiteWayfarerAcquisitionEngine;
const polygon=[{lat:35.65,lng:139.75},{lat:35.65,lng:139.76},{lat:35.66,lng:139.76},{lat:35.66,lng:139.75}];
const plan=engine.createPlan(polygon,{bufferMeters:200,maxTileMeters:500,cellLevel:14});
assert.ok(plan.tiles.length>1&&plan.tiles.length<=64);
assert.ok(plan.tiles.every(t=>engine.boundsSizeMeters(t).width<=501));
let active=0,peak=0;
const result=await engine.executePlan(plan,async tile=>{active++;peak=Math.max(peak,active);await Promise.resolve();active--;return {items:[{guid:tile.id}]};});
assert.equal(peak,1);
assert.equal(result.transportComplete,true);
assert.equal(result.sourceComplete,null);
assert.equal(result.coverageComplete,false);
const partial=await engine.executePlan(plan,async()=>{throw Error('synthetic');});
assert.equal(partial.transportComplete,false);
assert.equal(partial.coverageComplete,false);
const test=fs.readFileSync('lab/i4-4-live-test.js','utf8');
const launcher=fs.readFileSync('lab/i4-4-iphone-test-shortcut.js','utf8');
