assert.match(test,/sourceComplete:null,coverageComplete:false/);
assert.match(test,/TILE_LIMIT_EXCEEDED/);
assert.match(test,/schemaSummary,poiTypeSummary,shapeSummary/);
assert.match(test,/poiField:/);
assert.match(test,/nestedSummary/);
assert.match(test,/inspectArray\('gmo'\)/);
assert.match(test,/inspectArray\('categoryTags'\)/);
assert.match(test,/I4-6-gmo-v1/);
assert.match(launcher,/DIAGNOSTIC_VERSION_MISMATCH/);
assert.match(test,/diagnosticVersion:version/);
assert.match(test,/safeKey\(key\)/);
assert.doesNotMatch(test,/JSON\.stringify\(json\)/);
assert.match(test,/STALE_OR_UNCONFIRMED_POLYGON/);
