/* Private fixture runner only. Never commit user-provided KMZ or derived bytes.
 * node test/verify-real-kasai-add-kind.mjs /path/to/private.kmz
 */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import JSZip from 'jszip';
import {DOMParser,XMLSerializer} from '@xmldom/xmldom';
import {createIsolatedEditorSession} from '../integration/isolated-editor-session.mjs';
import {stageKmlInput} from '../core/stage-kmz.mjs';
import {diagnoseKmzCandidate} from '../core/diagnose-kmz-candidate.mjs';
const path=process.argv[2];if(!path)throw Error('Pass private Kasai KMZ path');
const bytes=new Uint8Array(readFileSync(path));
const fp=createHash('sha256').update(bytes).digest('hex');
assert.equal(fp,'1c57f66d8658515ec6959af55044423189fdf5b4c5941d84b9a5466f0ef5d162');
const deps={JSZip,DOMParser,XMLSerializer};
const memory=new Map([['next-lab-creative-v7','PRESERVE_OLD']]);
const storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const x=createIsolatedEditorSession({...deps,storage});
assert.equal((await x.prepare(bytes)).status,'REVIEW');assert.equal(x.acceptPrepared({confirmed:true}).applied,true);
const before=x.state(),target=before.records.find(p=>p.role==='existing'&&p.kind==='pokestop');
assert.ok(target);
let info=x.command({type:'add',poi:{role:'new',kind:'gym',title:'葛西専用一時テスト',memo:'テストのみ',lat:35.643,lng:139.857}},{confirmed:true});
assert.equal(info.ok,false,'25 cap must block addition without explicit deletion');
const remove=before.records.find(p=>p.role==='new'&&p.kind==='gym');assert.ok(remove);
assert.equal(x.command({type:'delete',id:remove.id},{confirmed:true}).ok,true);
assert.equal(x.command({type:'add',poi:{role:'new',kind:'gym',title:'葛西専用一時テスト',memo:'テストのみ',lat:35.643,lng:139.857}},{confirmed:true}).ok,true);
const extra=x.state().records.find(p=>p.title==='葛西専用一時テスト');assert.ok(extra);
assert.equal(x.state().circles.length,213);assert.equal(x.state().records.length,214);
assert.equal(x.command({type:'change-kind',id:target.id,kind:'gym'},{confirmed:true}).ok,true);
const out=await x.exportKmz(),st=await stageKmlInput(out.bytes,deps),diagnosis=diagnoseKmzCandidate(st);
assert.equal(diagnosis.disposition,'READY',JSON.stringify(diagnosis.issues));
assert.deepEqual([diagnosis.counts.existing,diagnosis.counts.newTotal,diagnosis.counts.circles,diagnosis.counts.activityAreas],[188,25,213,1]);
const get=(p,key)=>p.data.find(d=>d.name==='campsite.creative.'+key)?.value;
const changed=st.places.find(p=>get(p,'id')===target.id),added=st.places.find(p=>get(p,'id')===extra.id);
assert.equal(changed.folder,'既存 Gym');assert.equal(changed.styleUrl,'#creative-existing-gym');
assert.equal(changed.data.find(d=>d.name==='nextlab-layer').value,'existing-gym');
assert.equal(get(changed,'kind'),'gym');assert.equal(added.folder,'新規 Gym');
assert.equal(added.data.find(d=>d.name==='nextlab-layer').value,'new-gym');
assert.equal(added.styleUrl,'#creative-new-gym');
assert.equal(st.places.filter(p=>get(p,'circle-owner-id')===extra.id).length,1);
assert.equal(st.places.find(p=>get(p,'circle-owner-id')===extra.id).circleValid,true);
assert.equal((await x.saveDraft()).status,'SAVED');
const again=createIsolatedEditorSession({...deps,storage});assert.equal((await again.resumeDraft({confirmed:true})).applied,true);
assert.equal(again.state().records.find(p=>p.id===extra.id).title,'葛西専用一時テスト');
assert.equal(again.state().circles.length,213);assert.equal(memory.get('next-lab-creative-v7'),'PRESERVE_OLD');
assert.equal(x.undo().ok,true);assert.equal(x.state().records.find(p=>p.id===target.id).kind,'pokestop');
assert.equal(x.undo().ok,true);assert.equal(x.state().circles.length,212);
assert.equal(x.undo().ok,true);assert.equal(x.state().circles.length,213);
assert.equal(createHash('sha256').update(readFileSync(path)).digest('hex'),fp);
console.log('REAL_KASAI_ADD_KIND: PASS: existing 188/new 25, replace new POI at capped 25, owned circle correct, legacy folder+style+nextlab-layer moved, Undo 3 steps, journal resume, original file unchanged');
